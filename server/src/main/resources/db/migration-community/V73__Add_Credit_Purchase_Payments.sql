CREATE TABLE credit_purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(64) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    product_id BIGINT NOT NULL REFERENCES credit_products(id),
    credits NUMERIC(24,6) NOT NULL CHECK (credits > 0),
    price_amount NUMERIC(12,2) NOT NULL CHECK (price_amount > 0),
    wallet_team_id BIGINT NOT NULL DEFAULT current_wallet_team_id() REFERENCES teams(id),
    payment_method VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    provider_trade_no VARCHAR(128),
    expires_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_credit_purchase_orders_payment_method CHECK (payment_method IN ('alipay', 'wechat')),
    CONSTRAINT ck_credit_purchase_orders_platform_wallet CHECK (wallet_team_id = 0),
    CONSTRAINT ck_credit_purchase_orders_status CHECK (status IN ('pending', 'processing', 'paid', 'closed')),
    CONSTRAINT uk_credit_purchase_orders_provider_trade UNIQUE (payment_method, provider_trade_no)
);

COMMENT ON TABLE credit_purchase_orders IS '平台积分购买订单表';
COMMENT ON COLUMN credit_purchase_orders.id IS '订单内部标识';
COMMENT ON COLUMN credit_purchase_orders.order_no IS '平台商户订单号';
COMMENT ON COLUMN credit_purchase_orders.user_id IS '购买用户标识';
COMMENT ON COLUMN credit_purchase_orders.product_id IS '下单时选择的商品标识';
COMMENT ON COLUMN credit_purchase_orders.credits IS '下单时锁定的积分数量快照';
COMMENT ON COLUMN credit_purchase_orders.price_amount IS '下单时锁定的人民币金额快照，单位元';
COMMENT ON COLUMN credit_purchase_orders.wallet_team_id IS '积分到账钱包归属，固定为零表示平台钱包';
COMMENT ON COLUMN credit_purchase_orders.payment_method IS '支付方式：alipay支付宝、wechat微信预留';
COMMENT ON COLUMN credit_purchase_orders.status IS '订单状态：pending待支付、processing处理中、paid已支付、closed已关闭';
COMMENT ON COLUMN credit_purchase_orders.provider_trade_no IS '支付渠道交易号';
COMMENT ON COLUMN credit_purchase_orders.expires_at IS '订单过期时间';
COMMENT ON COLUMN credit_purchase_orders.paid_at IS '确认到账时间';
COMMENT ON COLUMN credit_purchase_orders.created_at IS '创建时间';
COMMENT ON COLUMN credit_purchase_orders.updated_at IS '最后更新时间';
CREATE INDEX idx_credit_purchase_orders_user_created ON credit_purchase_orders(user_id, created_at DESC, id DESC);
CREATE INDEX idx_credit_purchase_orders_pending_expiry ON credit_purchase_orders(status, expires_at) WHERE status = 'pending';
CREATE INDEX idx_credit_purchase_orders_wallet_status ON credit_purchase_orders(wallet_team_id, status, created_at DESC);
ALTER TABLE credit_purchase_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE credit_purchase_orders FORCE ROW LEVEL SECURITY;
CREATE POLICY credit_purchase_orders_platform_scope ON credit_purchase_orders
    USING (team_system_access() OR wallet_team_id = current_wallet_team_id())
    WITH CHECK (team_system_access() OR wallet_team_id = current_wallet_team_id());

