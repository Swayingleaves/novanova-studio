-- 积分商品、支付订单和支付宝支付流水。
CREATE TABLE credit_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credits NUMERIC(24,6) NOT NULL CHECK (credits > 0),
    price_amount NUMERIC(12,2) NOT NULL CHECK (price_amount > 0),
    sort_order INTEGER NOT NULL DEFAULT 100 CHECK (sort_order >= 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE credit_products IS '平台积分商品配置表';
COMMENT ON COLUMN credit_products.id IS '积分商品标识';
COMMENT ON COLUMN credit_products.credits IS '商品发放积分数量，购买后永久有效';
COMMENT ON COLUMN credit_products.price_amount IS '商品人民币价格，单位元';
COMMENT ON COLUMN credit_products.sort_order IS '前端展示排序，数值越小越靠前';
COMMENT ON COLUMN credit_products.enabled IS '是否允许用户购买';
COMMENT ON COLUMN credit_products.created_at IS '创建时间';
COMMENT ON COLUMN credit_products.updated_at IS '最后更新时间';
CREATE INDEX idx_credit_products_enabled_sort ON credit_products(enabled, sort_order, id);
ALTER TABLE credit_products ENABLE ROW LEVEL SECURITY;
ALTER TABLE credit_products FORCE ROW LEVEL SECURITY;
CREATE POLICY credit_products_platform_scope ON credit_products
    USING (team_system_access() OR current_team_id() = 0)
    WITH CHECK (team_system_access() OR current_team_id() = 0);

