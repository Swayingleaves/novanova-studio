-- 团队、成员、授权及配置继承。零号团队是平台空间，不参与团队管理列表。
CREATE TABLE teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_slug VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    introduction VARCHAR(2000) NOT NULL DEFAULT '',
    logo_url TEXT NOT NULL DEFAULT '',
    administrator_user_id BIGINT REFERENCES users(id),
    member_limit INTEGER NOT NULL CHECK (member_limit >= 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE teams IS '团队空间表，零号记录表示平台空间';
COMMENT ON COLUMN teams.id IS '团队标识，零表示平台空间';
COMMENT ON COLUMN teams.team_slug IS '唯一团队访问路径标识';
COMMENT ON COLUMN teams.name IS '团队名称';
COMMENT ON COLUMN teams.introduction IS '团队介绍';
COMMENT ON COLUMN teams.logo_url IS '团队标志地址，空字符串表示使用平台品牌';
COMMENT ON COLUMN teams.administrator_user_id IS '主管理员用户标识';
COMMENT ON COLUMN teams.member_limit IS '子账号数量上限，不包含主管理员';
COMMENT ON COLUMN teams.enabled IS '是否启用团队';
COMMENT ON COLUMN teams.created_at IS '创建时间';
COMMENT ON COLUMN teams.updated_at IS '最后更新时间';
INSERT INTO teams(id, team_slug, name, member_limit) VALUES (0, 'platform', 'Novanova Studio', 0);

CREATE TABLE team_members (
    team_id BIGINT NOT NULL REFERENCES teams(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    member_role VARCHAR(20) NOT NULL CHECK (member_role IN ('administrator', 'member')),
    member_status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (member_status IN ('active', 'disabled', 'removed')),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    removed_at TIMESTAMPTZ,
    PRIMARY KEY(team_id, user_id),
    CHECK (team_id > 0)
);
COMMENT ON TABLE team_members IS '用户与团队成员关系，移除后保留用于历史账目与余额恢复';
COMMENT ON COLUMN team_members.team_id IS '所属团队标识';
COMMENT ON COLUMN team_members.user_id IS '成员用户标识';
COMMENT ON COLUMN team_members.member_role IS '团队角色：administrator主管理员、member成员';
COMMENT ON COLUMN team_members.member_status IS '成员状态：active正常、disabled禁用、removed移除';
COMMENT ON COLUMN team_members.joined_at IS '最近加入时间';
COMMENT ON COLUMN team_members.removed_at IS '最近移除时间';
CREATE INDEX idx_team_members_user ON team_members(user_id, member_status, team_id);
CREATE UNIQUE INDEX uk_team_administrator ON team_members(team_id) WHERE member_role = 'administrator' AND member_status <> 'removed';

