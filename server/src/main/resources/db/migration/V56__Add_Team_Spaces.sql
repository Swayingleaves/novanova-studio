-- 父子关系除了外键存在性，还必须属于同一团队；外键自身的检查会绕过行级策略。
CREATE FUNCTION check_team_reference() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE referenced_team BIGINT; field_value TEXT;
BEGIN
    field_value := to_jsonb(NEW)->>TG_ARGV[1];
    IF field_value IS NULL THEN RETURN NEW; END IF;
    EXECUTE format('SELECT team_id FROM %I WHERE %I = ($1)::%s', TG_ARGV[0], TG_ARGV[2], TG_ARGV[3])
        INTO referenced_team USING field_value;
    IF referenced_team IS NULL OR referenced_team <> NEW.team_id THEN
        IF referenced_team = 0 AND TG_ARGV[0] IN ('script_templates', 'script_template_sections') THEN RETURN NEW; END IF;
        IF referenced_team = 0 AND TG_ARGV[0] = 'system_notifications' AND team_content_scope('notifications') = 0 THEN RETURN NEW; END IF;
        IF referenced_team = 0 AND TG_ARGV[0] IN ('platform_ai_model_configs', 'platform_object_storage_configs')
            AND TG_TABLE_NAME NOT LIKE 'platform_%' AND EXISTS (
                SELECT 1 FROM team_resource_grants WHERE team_id = NEW.team_id
                    AND resource_type = CASE WHEN TG_ARGV[0] = 'platform_ai_model_configs' THEN 'model' ELSE 'objectStorage' END
                    AND resource_id = field_value
            ) THEN RETURN NEW; END IF;
        RAISE EXCEPTION '关联数据不属于当前团队' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
COMMENT ON FUNCTION check_team_reference() IS '阻止通过已知外键向其他团队的项目或资源附加数据';
DO $$
DECLARE reference RECORD;
BEGIN
    FOR reference IN
        SELECT child.relname child_table, parent.relname parent_table, child_column.attname child_column,
               parent_column.attname parent_column, format_type(parent_column.atttypid, parent_column.atttypmod) column_type, constraint_record.oid
        FROM pg_constraint constraint_record
        JOIN pg_class child ON child.oid = constraint_record.conrelid
        JOIN pg_class parent ON parent.oid = constraint_record.confrelid
        JOIN pg_attribute child_column ON child_column.attrelid = child.oid AND child_column.attnum = constraint_record.conkey[1]
        JOIN pg_attribute parent_column ON parent_column.attrelid = parent.oid AND parent_column.attnum = constraint_record.confkey[1]
        WHERE constraint_record.contype = 'f' AND cardinality(constraint_record.conkey) = 1 AND parent.relname <> 'teams'
          AND EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = child.oid AND attname = 'team_id')
          AND EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = parent.oid AND attname = 'team_id')
    LOOP
        EXECUTE format('CREATE TRIGGER %I BEFORE INSERT OR UPDATE OF %I, team_id ON %I FOR EACH ROW EXECUTE FUNCTION check_team_reference(%L, %L, %L, %L)',
            'check_scope_' || reference.oid, reference.child_column, reference.child_table,
            reference.parent_table, reference.child_column, reference.parent_column, reference.column_type);
    END LOOP;
END $$;
