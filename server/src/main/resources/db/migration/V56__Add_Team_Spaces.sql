COMMENT ON COLUMN team_invitations.member_role IS '接受邀请后授予的团队角色';
COMMENT ON COLUMN team_invitations.invitation_status IS '邀请状态';
COMMENT ON COLUMN team_invitations.invited_by IS '邀请发起用户';
COMMENT ON COLUMN team_invitations.expires_at IS '邀请过期时间';
