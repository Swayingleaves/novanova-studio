-- 业务表统一隔离，包括只通过父项目引用的子表；已有数据属于平台空间。
DO $$
DECLARE table_name TEXT;
BEGIN
    FOR table_name IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND (
        tablename IN ('user_configs', 'canvas_projects', 'assets', 'generation_logs', 'media_files',
          'ai_generation_tasks', 'agent_session', 'agent_plan', 'agent_plan_task', 'creation_agent_request',
          'video_workflow_context', 'video_composition_tasks', 'user_notification_reads',
          'user_ai_channels', 'user_ai_model_configs', 'user_object_storage_configs', 'user_webdav_configs')
        OR tablename LIKE 'script_%' OR tablename LIKE 'comic_drama_%' OR tablename LIKE 'novel_adaptation_%'
        OR tablename LIKE 'story_bible_%' OR tablename LIKE 'episode_body_%' OR tablename LIKE 'episode_bodies_%'
    ) LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN team_id BIGINT NOT NULL DEFAULT current_team_id() REFERENCES teams(id)', table_name);
        EXECUTE format('COMMENT ON COLUMN %I.team_id IS ''所属团队空间，零表示平台空间''', table_name);
        EXECUTE format('CREATE INDEX %I ON %I(team_id)', 'idx_scope_' || table_name, table_name);
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', table_name);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', table_name);
        EXECUTE format('CREATE POLICY team_isolation ON %I USING (team_system_access() OR team_id = current_team_id()) WITH CHECK (team_system_access() OR team_id = current_team_id())', table_name);
    END LOOP;
END $$;

-- 平台资源授权只影响读取，团队不能更新或删除平台资源。
DO $$
DECLARE resource_table TEXT; content_table TEXT; module_name TEXT;
BEGIN
    FOREACH resource_table IN ARRAY ARRAY['platform_ai_channels', 'platform_ai_model_configs', 'platform_object_storage_configs'] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN team_id BIGINT NOT NULL DEFAULT current_team_id() REFERENCES teams(id)', resource_table);
        EXECUTE format('COMMENT ON COLUMN %I.team_id IS ''资源所属团队，零表示平台资源''', resource_table);
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', resource_table);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', resource_table);
        EXECUTE format('CREATE POLICY resource_owner_write ON %I FOR ALL USING (team_system_access() OR team_id = current_team_id()) WITH CHECK (team_system_access() OR team_id = current_team_id())', resource_table);
    END LOOP;
    CREATE POLICY granted_models ON platform_ai_model_configs FOR SELECT USING (team_id = 0 AND EXISTS (
        SELECT 1 FROM team_resource_grants WHERE team_id = current_team_id() AND resource_type = 'model' AND resource_id = model_config_id));
    CREATE POLICY granted_channels ON platform_ai_channels FOR SELECT USING (team_id = 0 AND EXISTS (
        SELECT 1 FROM team_resource_grants grants JOIN platform_ai_model_configs models ON grants.resource_id = models.model_config_id
        WHERE grants.team_id = current_team_id() AND grants.resource_type = 'model' AND models.channel_id = platform_ai_channels.channel_id));
    CREATE POLICY granted_storages ON platform_object_storage_configs FOR SELECT USING (team_id = 0 AND EXISTS (
        SELECT 1 FROM team_resource_grants WHERE team_id = current_team_id() AND resource_type = 'objectStorage' AND resource_id = storage_id));
    FOR content_table, module_name IN SELECT * FROM (VALUES ('prompt_library', 'prompts'), ('system_notifications', 'notifications'),
        ('generation_styles', 'styles'), ('skills', 'skills'), ('homepage_showcases', 'homepage')) modules LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN team_id BIGINT NOT NULL DEFAULT current_team_id() REFERENCES teams(id)', content_table);
        EXECUTE format('COMMENT ON COLUMN %I.team_id IS ''内容所属团队，零表示全局内容''', content_table);
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', content_table);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', content_table);
        EXECUTE format('CREATE POLICY effective_content ON %I FOR SELECT USING (team_system_access() OR team_id = team_content_scope(%L))', content_table, module_name);
        EXECUTE format('CREATE POLICY own_content_insert ON %I FOR INSERT WITH CHECK (team_id = current_team_id() AND team_id = team_content_scope(%L))', content_table, module_name);
        EXECUTE format('CREATE POLICY own_content_update ON %I FOR UPDATE USING (team_id = current_team_id() AND team_id = team_content_scope(%L)) WITH CHECK (team_id = current_team_id())', content_table, module_name);
        EXECUTE format('CREATE POLICY own_content_delete ON %I FOR DELETE USING (team_id = current_team_id() AND team_id = team_content_scope(%L))', content_table, module_name);
    END LOOP;
END $$;

