CREATE TABLE platform_credit_settings (
    id SMALLINT PRIMARY KEY DEFAULT 1,
    initial_credits INTEGER NOT NULL DEFAULT 100,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_platform_credit_settings_singleton CHECK (id = 1),
    CONSTRAINT ck_platform_credit_settings_initial_credits CHECK (initial_credits >= 0)
);

COMMENT ON TABLE platform_credit_settings IS '全站积分设置表';
COMMENT ON COLUMN platform_credit_settings.id IS '固定单行标识';
COMMENT ON COLUMN platform_credit_settings.initial_credits IS '新用户初始积分';
COMMENT ON COLUMN platform_credit_settings.created_at IS '创建时间';
COMMENT ON COLUMN platform_credit_settings.updated_at IS '更新时间';

